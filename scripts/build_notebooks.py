"""Generate self-contained Fabric notebooks from src/diva_lakehouse (single source).

Outputs (deterministic, no timestamps):
  fabric/<Name>.Notebook/.platform            Fabric Git integration system file (v2)
  fabric/<Name>.Notebook/notebook-content.py  Fabric notebook source format (PySpark)
  ipynb/<Name>.ipynb                          plain Jupyter notebooks for manual import

Every notebook embeds the full package source as strings and registers it with
a small import hook, so `import diva_lakehouse` works in Fabric without
uploading files or creating an Environment.

Usage:
  python scripts/build_notebooks.py            # write files
  python scripts/build_notebooks.py --check    # exit 1 if files are out of date
"""

