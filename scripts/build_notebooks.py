def module_source(mod: str) -> str:
    with open(os.path.join(SRC, f"{mod}.py"), encoding="utf-8") as fh:
        src = fh.read()
    if "'''" in src:
        raise ValueError(f"{mod}.py must not contain triple single quotes (used as embedding delimiter)")
    if not src.endswith("\n"):
        src += "\n"
    return src


def module_cell(mod: str) -> str:
    name = "diva_lakehouse" if mod == "__init__" else f"diva_lakehouse.{mod}"
    return f"# Embedded module {name} (generated from src/diva_lakehouse/{mod}.py)\n" \
           f"_diva_register({name!r}, r'''{module_source(mod)}''')\n"


def notebook_cells(name: str) -> list:
    cells = [params_cell(name), LOADER_CELL] + [module_cell(m) for m in MODULES] + [CONFIG_CELL]
    return cells + STAGE_CELLS[name]


# --------------------------------------------------------------- serializers
def _meta_block(obj: dict) -> str:
    lines = json.dumps(obj, indent=2).split("\n")
    return "\n".join("# META " + line if line else "# META" for line in lines)


def fabric_notebook_content(cells: list) -> str:
    out = ["# Fabric notebook source", "", "# METADATA ********************", "",
           _meta_block({"kernel_info": {"name": "synapse_pyspark"}, "dependencies": {}}), ""]
    cell_meta = _meta_block({"language": "python", "language_group": "synapse_pyspark"})
    for code in cells:
        for line in code.split("\n"):
            if line.startswith(FORBIDDEN_LINE_PREFIXES):
                raise ValueError(f"Cell line collides with Fabric source markers: {line!r}")
        out += ["# CELL ********************", "", code.rstrip("\n"), "",
                "# METADATA ********************", "", cell_meta, ""]
    return "\n".join(out)


def platform_file(name: str, description: str) -> str:
    obj = {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/gitIntegration/platformProperties/2.0.0/schema.json",
        "metadata": {"type": "Notebook", "displayName": name, "description": description},
        "config": {"version": "2.0", "logicalId": logical_id(name)},
    }
    return json.dumps(obj, indent=2) + "\n"


def ipynb(name: str, description: str, cells: list) -> str:
    def src(text):
        lines = text.rstrip("\n").split("\n")
        return [line + "\n" for line in lines[:-1]] + [lines[-1]]

    nb_cells = [{
        "cell_type": "markdown", "id": "intro", "metadata": {},
        "source": src(f"# {name}\n\n{description}\n\nGenerated from `src/diva_lakehouse` by "
                      "`scripts/build_notebooks.py`. Attach a default Lakehouse before running. "
                      "See `docs/setup-fabric.md`."),
    }]
    for i, code in enumerate(cells):
        meta = {"tags": ["parameters"]} if i == 0 else {}
        nb_cells.append({"cell_type": "code", "execution_count": None, "id": f"cell-{i:02d}",
                         "metadata": meta, "outputs": [], "source": src(code)})
    nb = {
        "cells": nb_cells,
        "metadata": {
            "kernelspec": {"display_name": "Synapse PySpark", "language": "Python", "name": "synapse_pyspark"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    return json.dumps(nb, indent=1, ensure_ascii=False) + "\n"


def render_all() -> dict:
    files = {}
    for name, desc in NOTEBOOKS:
        cells = notebook_cells(name)
        files[f"fabric/{name}.Notebook/.platform"] = platform_file(name, desc)
        files[f"fabric/{name}.Notebook/notebook-content.py"] = fabric_notebook_content(cells)
        files[f"ipynb/{name}.ipynb"] = ipynb(name, desc, cells)
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = ap.parse_args()
    files = render_all()
    stale = []
    for rel, content in files.items():
        path = os.path.join(ROOT, rel)
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current != content:
            stale.append(rel)
            if not args.check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(content)
    if args.check:
        if stale:
            print("Out of date (run python scripts/build_notebooks.py):\n  " + "\n  ".join(stale))
            return 1
        print(f"All {len(files)} generated notebook files are up to date.")
        return 0
    print(f"Wrote {len(stale)} file(s); {len(files) - len(stale)} unchanged.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
